export function getLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'it' || saved === 'en') return saved;
  } catch {}
  return 'it';
}

export function t(key, ...args) {
  const lang = getLang();
  const entry = dict[lang]?.[key] ?? dict.it[key];
  if (typeof entry === 'function') return entry(...args);
  return entry ?? key;
}

function applyMeta(lang) {
  document.documentElement.lang = lang;
  const ogLocale = document.querySelector('meta[property="og:locale"]');
  if (ogLocale) ogLocale.setAttribute('content', lang === 'en' ? 'en_US' : 'it_IT');
}

export function applyI18n(root = document) {
  const lang = getLang();
  applyMeta(lang);

  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const val = t(el.dataset.i18n);
    if (val != null) el.textContent = val;
  });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const val = t(el.dataset.i18nHtml);
    if (val != null) el.innerHTML = val;
  });
  root.querySelectorAll('[data-i18n-content]').forEach((el) => {
    const val = t(el.dataset.i18nContent);
    if (val != null) el.setAttribute('content', val);
  });
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    el.dataset.i18nAttr.split('|').forEach((pair) => {
      const [attr, key] = pair.split(':');
      if (attr && key) el.setAttribute(attr, t(key));
    });
  });
  if (root === document && document.title.length) {
    const titleKey = document.querySelector('title')?.dataset.i18n;
    if (titleKey) document.title = t(titleKey);
  }
}

export function setLang(lang) {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {}
  applyI18n();
  document.dispatchEvent(new CustomEvent('i18n:change', { detail: { lang } }));
}
